const supportedLanguages = [
  "de",
  "en",
  "ru",
  "it",
  "es",
  "ar",
  "tr",
  "th"
];

let currentLanguage = "de";

function normalizeLanguage(value) {
  const language = String(value || "de")
    .toLowerCase()
    .trim()
    .split("-")[0]
    .split("_")[0];

  return supportedLanguages.includes(language)
    ? language
    : "de";
}

function getValue(object, path) {
  return path
    .split(".")
    .reduce(
      (current, key) => current?.[key],
      object
    );
}

export function t(key, variables = {}) {
  const value =
    getValue(translations[currentLanguage], key) ??
    getValue(translations.de, key) ??
    key;

  if (typeof value !== "string") {
    return value;
  }

  return Object.entries(variables).reduce(
    (text, [name, replacement]) =>
      text.replaceAll(
        `{${name}}`,
        String(replacement ?? "")
      ),
    value
  );
}

export function getLanguage() {
  return currentLanguage;
}

export function getTranslationCount() {
  function countValues(value) {
    if (!value || typeof value !== "object") {
      return 0;
    }

    return Object.values(value).reduce(
      (sum, item) =>
        sum +
        (
          typeof item === "object"
            ? countValues(item)
            : 1
        ),
      0
    );
  }

  return countValues(
    translations[currentLanguage]
  );
}

export function setLanguage(language) {
  currentLanguage = normalizeLanguage(language);

  localStorage.setItem(
    "phoenix-v2-language",
    currentLanguage
  );

  const languageInformation =
    getLanguageInformation()[currentLanguage];

  document.documentElement.lang =
    currentLanguage;

  document.documentElement.dir =
    languageInformation?.direction || "ltr";

  window.dispatchEvent(
    new CustomEvent(
      "phoenix-v2:language-changed",
      {
        detail: {
          language: currentLanguage,
          direction:
            languageInformation?.direction || "ltr"
        }
      }
    )
  );

  return currentLanguage;
}

export function initializeLanguage() {
  return setLanguage(
    localStorage.getItem("phoenix-v2-language") ||
    localStorage.getItem("phoenix-language") ||
    "de"
  );
}

